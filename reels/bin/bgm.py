#!/usr/bin/env python3
"""The BGM store: every song we can reuse, plus songs spotted in reference reels but not prepared yet.
Usage: python3 bin/bgm.py            (prints the catalogue; also written to library/music/CATALOGUE.md)
Prepare a spotted song: .venv/bin/python bin/song.py <slug> "<title artist>" --ref refs/ana/<ref id>.mp3 --len 20 --mood "..."."""
import json
from pathlib import Path
import os

os.dup2(os.open(os.devnull, os.O_RDONLY), 0)  # ffmpeg reads stdin: in a shell `while read` loop it would eat the remaining commands

import os as _os
ROOT = Path(_os.environ.get("REEL_HOME") or Path(__file__).resolve().parent.parent)  # data dir (per brand)
ENGINE = Path(__file__).resolve().parent.parent
MUSIC, ANA = ROOT / "library/music", ROOT / "refs/ana"

ready = []
for f in sorted(MUSIC.glob("*.json")):
    if f.name.endswith((".lyrics.json", ".stt.json")):
        continue
    m = json.loads(f.read_text())
    lyr = "yes" if (MUSIC / f"{f.stem}.lyrics.json").exists() else ""
    ready.append(f"| {f.stem} | {m['query']} | {m.get('mood', '')} | {m['bpm']:.0f} | {m['start']:.1f}s | {m.get('ref') or ''} | {lyr} |")
prepared = {json.loads(f.read_text()).get("ref") for f in MUSIC.glob("*.json") if not f.name.endswith((".lyrics.json", ".stt.json"))}
queries = " ".join(json.loads(f.read_text())["query"].lower() for f in MUSIC.glob("*.json") if not f.name.endswith((".lyrics.json", ".stt.json")))
spotted = []
for f in sorted(ANA.glob("*.json")):
    if f.name.endswith(".stt.json"):
        continue
    r = json.loads(f.read_text())
    song = r.get("song") or ""
    title = song.split(" — ")[0].split(" (")[0].lower()
    if song and "failed" not in song and r["id"] not in prepared and title not in queries:
        spotted.append(f"| {song} | {r['id']} | {r.get('likes') or ''} | {r.get('creator') or ''} |")
md = ("# BGM catalogue (generated by bin/bgm.py, don't edit)\n\n## Ready (hook + beats prepared)\n"
      "| slug | song | mood | bpm | hook | from ref | lyrics |\n|---|---|---|---|---|---|---|\n" + "\n".join(ready) +
      "\n\n## Spotted in refs, not prepared\n| song | ref | likes | creator |\n|---|---|---|---|\n" + "\n".join(spotted) + "\n")
(MUSIC / "CATALOGUE.md").write_text(md)
print(md)
